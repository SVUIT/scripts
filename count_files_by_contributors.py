import pandas as pd, json
from urllib.parse import quote

SPREADSHEET_ID = "1arPrQDmujnKIvUaC648NmCt7dFkma7LitG9WyGt7t9M"  # copy từ URL sheet
SHEET_NAME     = "WIP"

CSV_URL = f"https://docs.google.com/spreadsheets/d/{SPREADSHEET_ID}/gviz/tq?tqx=out:csv&sheet={quote(SHEET_NAME)}"

df = pd.read_csv(CSV_URL, header=1, usecols=[0,2,3,4])
df.columns = ["name", "class", "submits", "files"]

# name: chuẩn hoá & lọc rác
df["name"] = df["name"].astype(str).str.strip()
df = df[df["name"].notna() & df["name"].ne("") & df["name"].str.lower().ne("nan")]

# class: chuẩn hoá để in cho đẹp
df["class"] = df["class"].astype(str).str.strip()
df.loc[df["class"].isna() | (df["class"].str.lower().isin(["", "nan"])), "class"] = "Unknown"

# số liệu: ép về int an toàn
for c in ["submits", "files"]:
    df[c] = (pd.to_numeric(df[c], errors="coerce").fillna(0).astype(int))

data = df.to_dict(orient="records")
print(json.dumps(data, ensure_ascii=False, indent=2))

# (tuỳ chọn) lưu file
with open("/content/contributors.json","w",encoding="utf-8") as f:
    json.dump(data, f, ensure_ascii=False, indent=2)
print("OK -> /content/contributors.json")